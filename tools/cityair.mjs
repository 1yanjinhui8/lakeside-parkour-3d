import fs from 'node:fs';
const PORT=9222, sleep=ms=>new Promise(r=>setTimeout(r,ms));
const T=(process.argv[2]||'0.72'), ARC=+(process.argv[3]||160), OUT=(process.argv[4]||'screenshots/city-air.png');
for (const t of (await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json()).filter(x=>x.type==='page')) await fetch(`http://127.0.0.1:${PORT}/json/close/${t.id}`).catch(()=>{});
await sleep(300);
const tgt=await (await fetch(`http://127.0.0.1:${PORT}/json/new?about:blank`,{method:'PUT'})).json();
const ws=new WebSocket(tgt.webSocketDebuggerUrl); await new Promise(r=>ws.addEventListener('open',r));
let seq=0; const pend=new Map();
ws.addEventListener('message',e=>{const m=JSON.parse(e.data); if(m.id&&pend.has(m.id)){pend.get(m.id)(m);pend.delete(m.id);}});
const send=(m,p={},tmo=180000)=>new Promise((a,b)=>{const id=++seq;pend.set(id,x=>x.error?b(new Error(JSON.stringify(x.error))):a(x.result));ws.send(JSON.stringify({id,method:m,params:p}));
  setTimeout(()=>{if(pend.has(id)){pend.delete(id);b(new Error('tmo'));}},tmo);});
const ev=async e=>{const r=await send('Runtime.evaluate',{expression:e,returnByValue:true,awaitPromise:true}); if(r.exceptionDetails) return {err:r.exceptionDetails.exception?.description}; return r.result?.value;};
await send('Page.enable'); await send('Runtime.enable');
await send('Emulation.setDeviceMetricsOverride',{width:1280,height:720,deviceScaleFactor:1,mobile:false});
await send('Page.navigate',{url:`http://127.0.0.1:8765/.perf-real.html?q=high&theme=city&t=${T}&v=${Date.now()}`},180000);
for(let i=0;i<240;i++){ if(await ev('typeof window.__game==="object" && !!window.__game.player')) break; await sleep(400); }
await ev(`(() => { const G=window.__game; G.startGame(); G.QUALITY.adaptive=false;
  G.CONFIG.speed.start=0; G.CONFIG.speed.max=0; G.S.state='playing'; G.Scene.phase='run'; G.Scene.segEnd=1e9;
  G.S.D=${ARC}; window.__wx && window.__wx.setTime && window.__wx.setTime(${T}); return 1; })()`);
await sleep(900);
// 冻结相机：站在街道上方 42m，俯角看向前方
await ev(`(() => { const G=window.__game, cam=G.camera;
  G.scene.fog.near=200; G.scene.fog.far=900;
  cam.fov=62; cam.updateProjectionMatrix();
  cam.position.set(0, 42, 26); cam.up.set(0,1,0); cam.lookAt(0, 18, -120);
  window.__freezeCam=true; return 1; })()`);
await sleep(700);
console.log(JSON.stringify(await ev(`({scene:window.__game.Scene.id, D:Math.round(window.__game.S.D)})`)));
const s=await send('Page.captureScreenshot',{format:'png'});
fs.writeFileSync(OUT, Buffer.from(s.data,'base64'));
console.log('shot', OUT);
process.exit(0);
